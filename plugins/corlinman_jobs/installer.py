def _existing_jobs() -> dict[str, dict]:
    from cron.jobs import load_jobs

    out: dict[str, dict] = {}
    for job in load_jobs():
        if isinstance(job, dict) and job.get("name"):
            out[str(job["name"])] = job
    return out


def _spec_job_fields(spec: JobSpec) -> dict[str, Any]:
    """The ``create_job`` keyword arguments this spec implies."""
    toolsets: Optional[list[str]]
    if spec.no_agent:
        toolsets = None
    elif spec.enabled_toolsets is None:
        toolsets = None
    elif len(spec.enabled_toolsets) == 0:
        toolsets = [NO_TOOLS_SENTINEL]
    else:
        toolsets = list(spec.enabled_toolsets)
    return {
        "prompt": spec.prompt,
        "schedule": spec.schedule,
        "name": spec.name,
        "deliver": spec.deliver,
        "script": spec.script,
        "no_agent": spec.no_agent,
        "enabled_toolsets": toolsets,
    }


def _job_differences(spec: JobSpec, job: Mapping[str, Any]) -> list[str]:
    """Fields where an already-installed job disagrees with its spec."""
    fields = _spec_job_fields(spec)
    want = {
        "schedule_display": spec.schedule,
        "script": fields["script"],
        "no_agent": fields["no_agent"],
        "deliver": fields["deliver"],
        "prompt": fields["prompt"] or "",
        "enabled_toolsets": fields["enabled_toolsets"],
    }
    out = []
    for key in _COMPARED_JOB_FIELDS:
        have = job.get(key)
        if key == "enabled_toolsets":
            have = list(have) if have else None
        if have != want[key]:
            out.append(key)
    return out


@dataclass(frozen=True)
class JobAction:
    """What the install would do to one cron job."""

    name: str
    #: ``create`` | ``exists``
    action: str
    reason: str
    spec: JobSpec


def job_actions(specs: Sequence[JobSpec] = JOB_SPECS) -> tuple[JobAction, ...]:
    """Classify every spec against the cron store. Read-only."""
    existing = _existing_jobs()
    out: list[JobAction] = []
    for spec in specs:
        job = existing.get(spec.name)
        if job is None:
            out.append(
                JobAction(spec.name, "create", "not present; will be created paused", spec)
            )
            continue
        state = "paused" if not job.get("enabled") else "ENABLED"
        differences = _job_differences(spec, job)
        detail = f"already installed as {job.get('id')} ({state})"
        if differences:
            detail += "; differs from the spec in " + ", ".join(differences)
        detail += ". Left untouched — remove it first if you want it rebuilt"
        out.append(JobAction(spec.name, "exists", detail, spec))
    return tuple(out)


