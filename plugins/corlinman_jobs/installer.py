def register_cli(subparser: argparse.ArgumentParser) -> None:
    """Wire the subcommands. Called by the plugin loader through register()."""
    subs = subparser.add_subparsers(dest="corlinman_jobs_action")

    plan_p = subs.add_parser(
        "plan", help="Show what an install would do. Writes nothing."
    )
    plan_p.add_argument("--only", action="append", default=None, metavar="JOB")

    install_p = subs.add_parser(
        "install", help="Install the jobs (created paused) and their scripts"
    )
    install_p.add_argument("--only", action="append", default=None, metavar="JOB")
    install_p.add_argument(
        "--force",
        action="store_true",
        help="Overwrite scripts this installer did not write (never waives preflight)",
    )

    status_p = subs.add_parser("status", help="Installed / paused / preflight report")
    status_p.add_argument("--only", action="append", default=None, metavar="JOB")


def corlinman_jobs_command(args: argparse.Namespace) -> int:
    """Dispatch. Returns a process exit code."""
    action = getattr(args, "corlinman_jobs_action", None)
    if not action:
        print("Usage: hermes corlinman-jobs {plan|install|status}")
        return 2
    only = getattr(args, "only", None)
    try:
        if action == "plan":
            current = plan(only)
            print(format_plan(current))
            return 1 if current.blocked else 0
        if action == "status":
            print(status(only))
            return 0
        if action == "install":
            result = install(only, force=bool(getattr(args, "force", False)))
            print(format_plan(result.plan))
            print("")
            if not result.ok:
                print(f"install failed: {result.error}", file=sys.stderr)
                return 1
            print(f"wrote {len(result.written)} file(s): {', '.join(result.written) or '-'}")
            for name, job_id in result.created:
                print(f"created (paused) {name} → {job_id}")
            for name in result.skipped:
                print(f"skipped {name} (already installed)")
            print(
                "\nEvery job is PAUSED. Enable one only after reading "
                "docs/migration-corlinman/D1-cron-port-notes.md:\n"
                "    hermes cron resume <name>"
            )
            return 0
    except KeyError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(f"unknown action {action!r}", file=sys.stderr)
    return 2


