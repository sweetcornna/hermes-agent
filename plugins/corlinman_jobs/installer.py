"""Install the migrated corlinman jobs into hermes's native cron.

The installer does three things and refuses to do a fourth:

1. **Copies** ``scripts/corlinman_jobs_lib.py`` verbatim into
   ``$HERMES_HOME/scripts/`` — hermes only runs cron scripts that resolve
   inside that directory (``cron/scheduler.py::_run_job_script``).
2. **Generates** one small entry script per job that needs one: an import of
   that library plus a single call to the matching ``main_*`` with the job's
   parameter bag baked in as literals. The generated text is a pure function
   of :mod:`plugins.corlinman_jobs.specs`, so re-running the installer either
   produces byte-identical files or a diff someone asked for.
3. **Creates** each job through ``cron.jobs.create_job`` and immediately
   pauses it.

The fourth thing — enabling anything — is not implemented here at all. Every
spec carries ``install_enabled=False`` and :func:`install` asserts it; turning
a job on is a deliberate ``hermes cron resume <name>`` by a human who has read
``docs/migration-corlinman/D1-cron-port-notes.md``. Three of these jobs post
to a real public QQ feed that already holds 19 real posts, and there is no
delete tool on the far side.

Two design points worth stating up front:

**The create→pause window is not a race.** ``create_job`` has no "create
paused" mode, so a job exists enabled for the microseconds between the two
calls. It cannot fire in that window: ``compute_next_run`` sets
``next_run_at`` to the next *future* occurrence of the cron expression and
``get_due_jobs`` only returns jobs whose ``next_run_at`` has passed. The
earliest possible fire is minutes away; the pause lands first. If
``pause_job`` somehow fails, :func:`install` says so loudly and names the job
rather than reporting success.

**Nothing is overwritten silently.** Every file the installer writes is
recorded in ``$HERMES_HOME/plugin-data/corlinman_jobs/install-manifest.json``
with its SHA-256. On the next run a file whose on-disk hash still matches the
recorded one is ours to refresh; a file that has drifted from both the plan
and the manifest is treated as hand-edited, reported as a ``conflict``, and
aborts the install before a single byte is written. ``--force`` overrides,
loudly.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Any, Mapping, Optional, Sequence

from . import preflight
from .preflight import Check
from .specs import JOB_SPECS, PERSONA_ID, JobSpec

#: The shared job-side library, copied verbatim.
LIB_FILENAME = "corlinman_jobs_lib.py"

#: Bookkeeping for "did we write this file, or did a human edit it".
MANIFEST_FILENAME = "install-manifest.json"
MANIFEST_VERSION = 1

#: Present in every generated entry script; makes the provenance greppable
#: on a host where nobody remembers what created these files.
GENERATED_MARKER = "generated by plugins.corlinman_jobs.installer"

#: hermes has no "no toolsets" spelling for a cron job. An empty
#: ``enabled_toolsets`` list is falsy, so ``_resolve_cron_enabled_toolsets``
#: skips it and falls back to the ``cron`` platform's configured toolsets —
#: i.e. an empty allowlist quietly means *more* tools, not fewer. The
#: ``no_mcp`` sentinel is the one value that survives to the agent as a
#: genuinely empty list: ``_merge_mcp_into_per_job_toolsets`` strips it and
#: returns ``[]``, and ``model_tools.get_tool_definitions`` treats ``[]``
#: (not None) as "include nothing". This is how ``hermes.diary_summary``
#: reproduces the source's ``tools_enabled=False``.
NO_TOOLS_SENTINEL = "no_mcp"

#: ``hermes.diary_summary``'s channel filter. The source hardcoded this list
#: in ``_diary_summary_action`` instead of reading it from the job metadata
#: (unlike ``_analysis_digest_action``, which takes ``metadata["channels"]``),
#: so it is not in the spec's verbatim parameter bag and is restated here.
#: specs.py holds what corlinman stored; the installer holds what corlinman
#: *did*.
DIARY_CHANNELS: tuple[str, ...] = ("telegram", "gateway")

#: Job fields the installer compares when an install finds a job already
#: present, so "already installed" can distinguish "identical" from "someone
#: changed it".
_COMPARED_JOB_FIELDS = (
    "schedule_display",
    "script",
    "no_agent",
    "deliver",
    "prompt",
    "enabled_toolsets",
)


