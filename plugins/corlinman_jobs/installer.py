def script_call(spec: JobSpec) -> tuple[str, dict[str, Any], bool]:
    """``(function name, keyword arguments, silence stdout)`` for one job.

    This is the single place the verbatim corlinman parameter bag in
    :mod:`~plugins.corlinman_jobs.specs` is translated into a call into
    :mod:`corlinman_jobs_lib`. Keeping it in one function means a parameter
    can only be misread once.

    Raises ``KeyError`` for a job that declares a ``script`` this table does
    not know about — better than generating a script that fails at 07:07.
    """
    params: Mapping[str, Any] = spec.params

    if spec.name == "hermes.daily_agenda":
        return (
            "main_daily_agenda",
            {
                "agenda_path": str(params["agenda_path"]),
                "timezone": spec.timezone,
            },
            False,
        )
    if spec.name == "hermes.analysis_digest":
        return (
            "main_analysis_material",
            {
                "user_id": str(params["user_id"]),
                "channels": [str(c) for c in params["channels"]],
                "timezone": spec.timezone,
            },
            False,
        )
    if spec.name == "hermes.diary_summary":
        return (
            "main_diary_material",
            {
                "user_id": str(params["user_id"]),
                # Not from params — see DIARY_CHANNELS.
                "channels": list(DIARY_CHANNELS),
                "timezone": spec.timezone,
            },
            False,
        )
    if spec.name == "hermes.youtube_daily":
        return (
            "main_youtube_state",
            {
                "job_name": spec.name,
                "channels": [str(c) for c in params["youtube_channels"]],
                "state_file": str(params["state_file"]),
            },
            False,
        )
    if spec.name == "hermes.qzone_daily":
        return (
            "main_qzone_recent_posts",
            {
                # The cron subprocess environment strips hermes-owned
                # PYTHONPATH entries (tools/environments/local.py::
                # _strip_hermes_owned_pythonpath), so the repository root has
                # to be handed over explicitly for `import plugins.qzone`.
                "repo_root": str(repo_root()),
                "persona_id": str(params["persona_id"]),
            },
            False,
        )
    if spec.name == "persona.decay":
        return (
            "main_grantley_decay",
            {
                "script_path": str(grantley_decay_script()),
                "persona_id": PERSONA_ID,
            },
            # grantley_job.py prints its result payload as JSON on stdout. For
            # a no_agent job stdout IS the delivered message, and an hourly
            # "{"ok": true, "rows_changed": 0}" is noise nobody asked for —
            # corlinman's decay delivered nothing. Routing it to stderr makes
            # the tick silent on success (hermes treats empty stdout as
            # "nothing to report") while a non-zero exit still fails the job
            # loudly and carries the payload into the error report.
            True,
        )
    raise KeyError(
        f"{spec.name} declares script={spec.script!r} but installer.script_call "
        "has no entry for it"
    )


def _py_literal(value: Any, indent: int = 4) -> str:
    """Render *value* as a deterministic Python literal.

    Deterministic because drift detection compares bytes: the same spec must
    always render to the same file, or every install would report a conflict.
    """
    if value is None or isinstance(value, (bool, int, float, str)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        if not value:
            return "[]"
        pad = " " * (indent + 4)
        body = "".join(f"{pad}{_py_literal(item, indent + 4)},\n" for item in value)
        return "[\n" + body + " " * indent + "]"
    raise TypeError(f"cannot bake {type(value).__name__} into a generated script")


def render_entry_script(spec: JobSpec) -> str:
    """The full text of one job's generated entry script."""
    function, kwargs, silent = script_call(spec)
    args = "".join(
        f"    {key}={_py_literal(kwargs[key])},\n" for key in sorted(kwargs)
    )
    header = (
        "#!/usr/bin/env python3\n"
        f'"""{spec.name} — {GENERATED_MARKER}.\n'
        "\n"
        "Do not edit. Re-run `hermes corlinman-jobs install` to regenerate;\n"
        "local edits are detected and refused rather than overwritten.\n"
        f'"""\n\n'
    )
    if not silent:
        return (
            header
            + f"from {LIB_FILENAME[:-3]} import {function}\n"
            "\n"
            f"raise SystemExit({function}(\n{args}))\n"
        )
    return (
        header
        + "import contextlib\n"
        "import sys\n"
        "\n"
        f"from {LIB_FILENAME[:-3]} import {function}\n"
        "\n"
        "with contextlib.redirect_stdout(sys.stderr):\n"
        f"    _code = {function}(\n{args}    )\n"
        "raise SystemExit(_code)\n"
    )


def planned_files(specs: Sequence[JobSpec] = JOB_SPECS) -> dict[str, str]:
    """``filename -> content`` for everything the install would write.

    The library comes first so a reader of the plan sees the dependency
    before its dependents.
    """
    files: dict[str, str] = {}
    scripted = [spec for spec in specs if spec.script]
    if scripted:
        files[LIB_FILENAME] = source_lib_path().read_text(encoding="utf-8")
    for spec in scripted:
        files[str(spec.script)] = render_entry_script(spec)
    return files


# ---------------------------------------------------------------------------
# Drift detection
# ---------------------------------------------------------------------------


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def read_manifest() -> dict:
    """The last install's record, or an empty one. Never raises."""
    try:
        raw = json.loads(manifest_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return raw if isinstance(raw, dict) else {}


def _recorded_hashes() -> dict[str, str]:
    files = read_manifest().get("files")
    if not isinstance(files, dict):
        return {}
    return {str(k): str(v) for k, v in files.items()}


@dataclass(frozen=True)
class FileAction:
    """What the install would do to one file in ``$HERMES_HOME/scripts/``."""

    filename: str
    path: Path
    #: ``create`` | ``update`` | ``unchanged`` | ``conflict``
    action: str
    reason: str

    @property
    def blocking(self) -> bool:
        return self.action == "conflict"


def file_actions(specs: Sequence[JobSpec] = JOB_SPECS) -> tuple[FileAction, ...]:
    """Classify every planned file against what is on disk. Read-only."""
    recorded = _recorded_hashes()
    directory = scripts_dir()
    out: list[FileAction] = []
    for filename, content in planned_files(specs).items():
        target = directory / filename
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError:
            out.append(
                FileAction(filename, target, "create", "not present in this profile")
            )
            continue
        if existing == content:
            out.append(FileAction(filename, target, "unchanged", "already current"))
            continue
        existing_hash = _sha256(existing)
        if recorded.get(filename) == existing_hash:
            out.append(
                FileAction(
                    filename,
                    target,
                    "update",
                    "installed by a previous run; the repository copy has changed",
                )
            )
            continue
        out.append(
            FileAction(
                filename,
                target,
                "conflict",
                "on disk but not written by this installer (hand-edited, or "
                "installed before the manifest existed) — inspect it, then "
                "re-run with --force to overwrite",
            )
        )
    return tuple(out)


def script_drift(specs: Sequence[JobSpec] = JOB_SPECS) -> dict[str, str]:
    """``filename -> "ok" | "missing" | "stale"``.

    The vocabulary preflight's ``check_scripts_installed`` speaks. A
    ``conflict`` reports as ``stale`` there — from the *enable* gate's point
    of view a hand-edited script and an outdated one are the same hazard,
    "the file running at 22:21 is not the file that was reviewed". The
    installer keeps the finer distinction; see :func:`file_actions`.
    """
    mapping = {
        "create": "missing",
        "update": "stale",
        "conflict": "stale",
        "unchanged": "ok",
    }
    return {action.filename: mapping[action.action] for action in file_actions(specs)}


