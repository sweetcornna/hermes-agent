def needs_qq(spec: JobSpec) -> bool:
    """Whether this job talks to QQ, and so needs the QQ preflight checks."""
    return "onebot" in (spec.enabled_toolsets or ())


def select_specs(only: Optional[Sequence[str]] = None) -> tuple[JobSpec, ...]:
    """Resolve a ``--only`` selection to specs, rejecting unknown names."""
    if not only:
        return JOB_SPECS
    wanted = list(only)
    known = {spec.name: spec for spec in JOB_SPECS}
    missing = [name for name in wanted if name not in known]
    if missing:
        raise KeyError(
            f"unknown job(s): {', '.join(missing)}; known: {', '.join(sorted(known))}"
        )
    return tuple(spec for spec in JOB_SPECS if spec.name in set(wanted))


@dataclass(frozen=True)
class Plan:
    """Everything an install would do, computed without doing any of it."""

    specs: tuple[JobSpec, ...]
    files: tuple[FileAction, ...]
    jobs: tuple[JobAction, ...]
    checks: tuple[Check, ...]
    scripts_dir: Path

    @property
    def blocking_checks(self) -> tuple[Check, ...]:
        return tuple(check for check in self.checks if check.blocking)

    @property
    def conflicts(self) -> tuple[FileAction, ...]:
        return tuple(action for action in self.files if action.blocking)

    @property
    def blocked(self) -> bool:
        return bool(self.blocking_checks or self.conflicts)

    @property
    def would_write(self) -> tuple[FileAction, ...]:
        return tuple(a for a in self.files if a.action in {"create", "update", "conflict"})

    @property
    def would_create(self) -> tuple[JobAction, ...]:
        return tuple(a for a in self.jobs if a.action == "create")


def plan(only: Optional[Sequence[str]] = None) -> Plan:
    """Compute the install plan. **No side effects of any kind.**

    Not one byte is written, no directory is created, no job is touched and
    no model, QQ session or Telegram API is contacted. The preflight checks
    read configuration and the qzone ledgers; that is the extent of it.

    ``include_scripts=False`` on the preflight run is deliberate: the script
    check exists to gate *enabling* a job, and asking it before an install
    would fail every fresh profile for not yet having the files this install
    is about to write.
    """
    specs = select_specs(only)
    checks = preflight.run_checks(
        include_qq=any(needs_qq(spec) for spec in specs),
        include_scripts=False,
    )
    return Plan(
        specs=specs,
        files=file_actions(specs),
        jobs=job_actions(specs),
        checks=tuple(checks),
        scripts_dir=scripts_dir(),
    )


def format_plan(plan_obj: Plan) -> str:
    """Render a plan for a terminal. Pure formatting."""
    lines: list[str] = []
    lines.append(f"corlinman → hermes cron install plan ({len(plan_obj.specs)} job(s))")
    lines.append(f"  profile scripts dir: {plan_obj.scripts_dir}")
    lines.append("")

    lines.append("preflight")
    for check in plan_obj.checks:
        mark = {preflight.OK: "ok  ", preflight.WARN: "warn", preflight.FAIL: "FAIL"}[
            check.level
        ]
        lines.append(f"  [{mark}] {check.key}: {check.message}")
        if check.detail:
            lines.append(f"         {check.detail}")
    lines.append("")

    lines.append("files")
    if not plan_obj.files:
        lines.append("  (none — the selected jobs need no scripts)")
    for action in plan_obj.files:
        lines.append(f"  {action.action:<9} {action.filename} — {action.reason}")
    lines.append("")

    lines.append("jobs")
    for action in plan_obj.jobs:
        spec = action.spec
        mode = "no_agent script" if spec.no_agent else "agent"
        lines.append(
            f"  {action.action:<9} {spec.name}  [{spec.schedule}]  {mode}  "
            f"→ {spec.deliver}"
        )
        lines.append(f"            {action.reason}")
        if action.action == "create":
            lines.append(f"            paused on creation: {spec.disabled_reason}")
            if spec.writes_public_feed:
                lines.append(
                    "            WRITES A REAL PUBLIC QQ FEED when enabled — "
                    "no undo exists"
                )
    lines.append("")

    if plan_obj.blocked:
        lines.append("BLOCKED — nothing would be installed:")
        for check in plan_obj.blocking_checks:
            lines.append(f"  preflight {check.key}: {check.message}")
        for action in plan_obj.conflicts:
            lines.append(f"  file {action.filename}: {action.reason}")
    else:
        lines.append(
            f"ready: {len(plan_obj.would_write)} file(s) to write, "
            f"{len(plan_obj.would_create)} job(s) to create (all paused)"
        )
    return "\n".join(lines)


