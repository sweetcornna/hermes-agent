@dataclass(frozen=True)
class InstallResult:
    """Outcome of a real install."""

    plan: Plan
    ok: bool
    error: str = ""
    written: tuple[str, ...] = ()
    created: tuple[tuple[str, str], ...] = ()
    skipped: tuple[str, ...] = ()
    #: Jobs that were created but could not be paused. Non-empty means a job
    #: is live that should not be; the caller must treat this as an incident.
    unpaused: tuple[str, ...] = ()


def install(
    only: Optional[Sequence[str]] = None,
    *,
    force: bool = False,
) -> InstallResult:
    """Write the scripts and create the jobs, paused.

    Aborts before writing anything when preflight reports a ``FAIL`` or when
    a file on disk was not written by this installer. ``force=True`` waives
    only the second of those — a failing preflight is never waivable, because
    every one of those checks guards against a silently wrong result (a
    schedule an hour off, a dedup ledger read from the wrong path) rather
    than an error somebody would notice.
    """
    current = plan(only)

    if current.blocking_checks:
        return InstallResult(
            plan=current,
            ok=False,
            error="preflight failed: "
            + "; ".join(f"{c.key}: {c.message}" for c in current.blocking_checks),
        )
    if current.conflicts and not force:
        return InstallResult(
            plan=current,
            ok=False,
            error="local edits would be overwritten: "
            + ", ".join(a.filename for a in current.conflicts)
            + " (re-run with --force to overwrite)",
        )

    for spec in current.specs:
        # A belt-and-braces read of the invariant the whole migration rests
        # on. If a spec ever grows install_enabled=True, stop here rather
        # than discovering it when a QQ post appears.
        if spec.install_enabled:
            return InstallResult(
                plan=current,
                ok=False,
                error=f"{spec.name} has install_enabled=True; refusing to install "
                "a job the migration is not allowed to enable",
            )

    directory = scripts_dir()
    directory.mkdir(parents=True, exist_ok=True)
    contents = planned_files(current.specs)
    written: list[str] = []
    hashes = _recorded_hashes()
    for action in current.files:
        if action.action == "unchanged":
            hashes[action.filename] = _sha256(contents[action.filename])
            continue
        text = contents[action.filename]
        action.path.write_text(text, encoding="utf-8")
        hashes[action.filename] = _sha256(text)
        written.append(action.filename)

    from cron.jobs import create_job, pause_job

    created: list[tuple[str, str]] = []
    skipped: list[str] = []
    unpaused: list[str] = []
    for job_action in current.jobs:
        if job_action.action != "create":
            skipped.append(job_action.name)
            continue
        spec = job_action.spec
        job = create_job(**_spec_job_fields(spec))
        paused = pause_job(job["id"], reason=spec.disabled_reason)
        if paused is None or paused.get("enabled"):
            unpaused.append(spec.name)
        created.append((spec.name, str(job["id"])))

    _write_manifest(hashes, created)

    return InstallResult(
        plan=current,
        ok=not unpaused,
        error=(
            "created but NOT paused: " + ", ".join(unpaused) + " — pause them by hand now"
            if unpaused
            else ""
        ),
        written=tuple(written),
        created=tuple(created),
        skipped=tuple(skipped),
        unpaused=tuple(unpaused),
    )


def _write_manifest(hashes: Mapping[str, str], created: Sequence[tuple[str, str]]) -> None:
    """Record what we wrote, so the next run can tell our files from edits."""
    previous = read_manifest()
    jobs = previous.get("jobs")
    jobs = dict(jobs) if isinstance(jobs, dict) else {}
    jobs.update({name: job_id for name, job_id in created})
    payload = {
        "version": MANIFEST_VERSION,
        "repo_root": str(repo_root()),
        "files": dict(sorted(hashes.items())),
        "jobs": dict(sorted(jobs.items())),
    }
    path = manifest_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".new")
    tmp.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


def status(only: Optional[Sequence[str]] = None) -> str:
    """Post-install readiness report, including the enable-time script check."""
    specs = select_specs(only)
    checks = preflight.run_checks(
        include_qq=any(needs_qq(spec) for spec in specs),
        include_scripts=True,
    )
    existing = _existing_jobs()
    lines = ["corlinman job status", ""]
    for check in checks:
        mark = {preflight.OK: "ok  ", preflight.WARN: "warn", preflight.FAIL: "FAIL"}[
            check.level
        ]
        lines.append(f"  [{mark}] {check.key}: {check.message}")
    lines.append("")
    for spec in specs:
        job = existing.get(spec.name)
        if job is None:
            lines.append(f"  {spec.name}: NOT INSTALLED")
            continue
        state = "paused" if not job.get("enabled") else "ENABLED"
        lines.append(
            f"  {spec.name}: {state}  id={job.get('id')}  "
            f"next={job.get('next_run_at')}  last={job.get('last_status')}"
        )
    return "\n".join(lines)


