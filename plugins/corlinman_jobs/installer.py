def repo_root() -> Path:
    """The hermes checkout holding this plugin."""
    return Path(__file__).resolve().parents[2]


def source_lib_path() -> Path:
    """In-tree copy of the job-side library — the thing that gets copied."""
    return Path(__file__).resolve().parent / "scripts" / LIB_FILENAME


def hermes_home() -> Path:
    """The active profile home, resolved fresh on every call.

    Deliberately not cached: tests and embedders re-point ``HERMES_HOME``
    after import, and a cached value here would write the generated scripts
    into whichever profile happened to be active when the module loaded.
    """
    from hermes_constants import get_hermes_home

    return Path(get_hermes_home())


def scripts_dir() -> Path:
    """``$HERMES_HOME/scripts`` — the only directory cron will run from."""
    return hermes_home() / "scripts"


def state_dir() -> Path:
    """Where the install manifest lives. Same directory the jobs use."""
    return hermes_home() / "plugin-data" / "corlinman_jobs"


def manifest_path() -> Path:
    return state_dir() / MANIFEST_FILENAME


def grantley_decay_script() -> Path:
    """Absolute path to ``grantley_job.py``, deployed copy preferred.

    ``persona.decay`` runs plugins/grantley's decay in place rather than
    copying it: that script resolves its package by walking up from its own
    ``__file__``, so a copy in ``$HERMES_HOME/scripts/`` would import
    nothing. The deployed copy under ``$HERMES_HOME/plugins/grantley/`` is
    preferred because that is the one ``plugins/memory`` actually loads as
    the memory provider — running decay against the repo copy while the
    provider serves the deployed one would decay a different database.
    """
    deployed = hermes_home() / "plugins" / "grantley" / "scripts" / "grantley_job.py"
    if deployed.is_file():
        return deployed
    return repo_root() / "plugins" / "grantley" / "scripts" / "grantley_job.py"


